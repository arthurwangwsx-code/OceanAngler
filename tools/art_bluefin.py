    image('Bluefin_MetallicSmoothness',np.dstack((np.zeros((h,w,3)),1-roughness)),True)
    # Two padded palette regions share one material/submesh: electric blue for
    # second dorsal/anal/caudal; muted grey-bronze for first dorsal and paired fins.
    fy,fx=np.mgrid[0:512,0:512];fu=np.clip((fx-4)/503,0,1);fv=fy/511
