def make_maps():
    h,w=1024,2048;y,x=np.mgrid[0:h,0:w];u=x/(w-1);v=y/(h-1);z=np.cos(v*math.tau)
    upper=np.clip((z+.1)/1.1,0,1);upper=upper*upper*(3-2*upper)
    silver=np.array([.44,.52,.48]);brass=np.array([.22,.28,.18]);color=silver[None,None,:]*(1-upper[:,:,None])+brass[None,None,:]*upper[:,:,None]
    belly=np.clip((-z-.12)/.88,0,1);color=color*(1-belly[:,:,None]) + np.array([.52,.59,.53])*belly[:,:,None]
    band=np.exp(-((z-.22)/.19)**2);color+=band[:,:,None]*np.array([-.015,.01,.04])
    rng=np.random.default_rng(6931);noise=rng.normal(0,.004,(h,w));color+=noise[:,:,None]
    # Fine overlapping scale relief; head and caudal peduncle are deliberately smoother.
    sy=v*80;sx=u*140+(np.floor(sy)%2)*.5;dx=(sx%1-.5)*2;dy=sy%1
    arc=np.exp(-((dy-(.28+.35*dx*dx))/.045)**2)
    mask=np.clip((u-.15)*8,0,1)*np.clip((.98-u)*12,0,1)
    relief=arc*mask*.003+noise*.012;color-=arc[:,:,None]*mask[:,:,None]*.010
    # Irregular blue-black spots on dorsal/flank regions; never a repeated tile.
    for _ in range(900):
        cx=rng.uniform(.22,.92)*w;cy=rng.uniform(0,h)
        if math.cos(cy/(h-1)*math.tau)<-.12:continue
        rx=rng.uniform(1.8,4.2);px=-1.04+2*cx/(w-1);phi=cy/(h-1)*math.tau
        top=np.interp(px,[p[0] for p in profile],[p[1] for p in profile]);width=np.interp(px,[p[0] for p in profile],[p[3] for p in profile])
        # Compensate cylindrical UV stretching using the local physical metric,
        # rather than painting circles in texture pixels that become long slits.
        tangent=math.tau*math.hypot(width*math.cos(phi),top*math.sin(phi))/(h-1)
        ry=rx*(2/(w-1))/max(tangent,.0002)
        x0=max(0,int(cx-rx*2));x1=min(w,int(cx+rx*2)+1);y0=max(0,int(cy-ry*2));y1=min(h,int(cy+ry*2)+1)
        yy,xx=np.mgrid[y0:y1,x0:x1];dot=np.exp(-((xx-cx)/rx)**2-((yy-cy)/ry)**2)*.8
        spot=np.array([.018,.065,.12]) if rng.random()<.55 else np.array([.018,.033,.03])
        color[y0:y1,x0:x1]=color[y0:y1,x0:x1]*(1-dot[:,:,None])+spot*dot[:,:,None]
    gy,gx=np.gradient(relief);normal=np.stack((-gx*95,-gy*95,np.ones_like(gx)),axis=2);normal/=np.linalg.norm(normal,axis=2)[:,:,None]
