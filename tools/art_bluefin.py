    gy,gx=np.gradient(fold,1/511,1/511);fn=np.stack((-gx/.025,-gy/.20,np.ones_like(gx)),axis=2);fn/=np.linalg.norm(fn,axis=2)[:,:,None]
    fin_normal=image('Bluefin_Fin_Normal',np.concatenate((fn*.5+.5,fn*.5+.5),axis=1),True)
